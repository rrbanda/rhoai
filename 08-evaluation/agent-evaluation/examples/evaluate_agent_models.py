"""Evaluate multiple LLMs on a synthetic MCP benchmark using LLM-as-judge scoring.

Loads benchmark tasks generated by generate_agent_benchmark.py, runs each model
through the same LangGraph agent (only the LLM is swapped), then scores tool-use
quality with both programmatic metrics and an LLM judge.

Pipeline stages:
  1. Load benchmark tasks (questions + expert gold-standard traces)
  2. For each model + server combination:
     a. AgentBlock sends tasks to the LangGraph agent with the target model
     b. AgentResponseExtractorBlock extracts text and tool traces
     c. Programmatic metrics compare tool usage against the expert trace
     d. LLM-as-judge flow scores traces on 6 quality dimensions
  3. Aggregate scores and produce rankings

Usage:
    export OPENAI_API_KEY="your-api-key"
    export JUDGE_MODEL="openai/gpt-4o"

    python evaluate_agent_models.py \\
        --benchmark benchmark_tasks.jsonl \\
        --agent-urls '{"Weather Data": "http://localhost:2024"}' \\
        --models gpt-4o gpt-4o-mini \\
        --output evaluation_results.jsonl
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from datasets import Dataset
from dotenv import load_dotenv

from sdg_hub import Flow, FlowRegistry
from sdg_hub.core.blocks.agent import AgentBlock, AgentResponseExtractorBlock


# ---------------------------------------------------------------------------
# Trace utilities (inline to keep the script self-contained)
# ---------------------------------------------------------------------------

def normalize_tool_trace(raw_trace: list[dict] | str) -> list[dict]:
    """Normalize a tool trace to canonical format: [{name, input, output}, ...]."""
    if isinstance(raw_trace, str):
        raw_trace = json.loads(raw_trace)
    if not isinstance(raw_trace, list):
        return []

    cleaned: list[dict] = []
    pending: dict[str, dict] = {}

    for entry in raw_trace:
        if not isinstance(entry, dict):
            continue

        if entry.get("role") == "assistant" and entry.get("tool_calls"):
            for tc in entry["tool_calls"]:
                func = tc.get("function", {})
                args = func.get("arguments", "{}")
                if isinstance(args, str):
                    try:
                        args = json.loads(args)
                    except (json.JSONDecodeError, TypeError):
                        args = {}
                call: dict = {"name": func.get("name", ""), "input": args}
                tc_id = tc.get("id")
                if tc_id:
                    pending[tc_id] = call
                cleaned.append(call)

        elif entry.get("role") == "tool":
            tc_id = entry.get("tool_call_id")
            content = entry.get("content", "")
            if tc_id and tc_id in pending:
                pending[tc_id]["output"] = content
            elif cleaned and "output" not in cleaned[-1]:
                cleaned[-1]["output"] = content

        elif entry.get("type") == "tool_use":
            if "tool_calls" in entry:
                for tc in entry["tool_calls"]:
                    call = {"name": tc.get("name", ""), "input": tc.get("args", {})}
                    tc_id = tc.get("id")
                    if tc_id:
                        pending[tc_id] = call
                    cleaned.append(call)
            elif "name" in entry:
                step: dict = {"name": entry["name"], "input": entry.get("tool_input", {})}
                if entry.get("output"):
                    step["output"] = entry["output"]
                cleaned.append(step)

        elif entry.get("type") == "tool_result":
            tc_id = entry.get("tool_call_id") or entry.get("id")
            if tc_id and tc_id in pending:
                pending[tc_id]["output"] = entry.get("content", "")
            elif cleaned and "output" not in cleaned[-1]:
                cleaned[-1]["output"] = entry.get("content", "")

    return cleaned


def extract_tool_names(trace: list[dict]) -> list[str]:
    """Extract ordered list of tool names from a canonical trace."""
    return [step["name"] for step in trace if "name" in step]


def format_trace_for_judge(
    tool_trace: list[dict],
    max_args_len: int = 300,
    max_output_len: int = 200,
) -> str:
    """Format a canonical tool trace as a readable string for the judge prompt."""
    if not tool_trace:
        return "  No tool calls made."
    lines = []
    for i, step in enumerate(tool_trace, 1):
        args_str = json.dumps(step.get("input", {}), ensure_ascii=False)
        if len(args_str) > max_args_len:
            args_str = args_str[:max_args_len] + "..."
        line = f"  [{i}] {step['name']}({args_str})"
        output = step.get("output")
        if output:
            out_str = str(output)
            if len(out_str) > max_output_len:
                out_str = out_str[:max_output_len] + "..."
            line += f"\n      -> {out_str}"
        lines.append(line)
    return "\n".join(lines)


def compute_tool_metrics(
    model_tools: list[str],
    expert_tools: list[str],
    model_trace: list[dict] | None = None,
    expert_trace: list[dict] | None = None,
) -> dict[str, float]:
    """Compute tool recall, precision, order match, and parameter similarity."""
    model_set, expert_set = set(model_tools), set(expert_tools)
    if not expert_set:
        return {"tool_recall": 1.0, "tool_precision": 1.0, "order_match": 1.0, "param_match": 1.0}

    intersection = model_set & expert_set
    recall = len(intersection) / len(expert_set)
    precision = len(intersection) / len(model_set) if model_set else 0.0

    m, n = len(model_tools), len(expert_tools)
    dp = [[0] * (n + 1) for _ in range(m + 1)]
    for i in range(1, m + 1):
        for j in range(1, n + 1):
            dp[i][j] = (
                dp[i - 1][j - 1] + 1
                if model_tools[i - 1] == expert_tools[j - 1]
                else max(dp[i - 1][j], dp[i][j - 1])
            )
    order = dp[m][n] / len(expert_tools)

    param_match = 0.0
    if model_trace and expert_trace:
        matched, total = 0, 0
        available = list(range(len(model_trace)))
        for et in expert_trace:
            for idx in available:
                mt = model_trace[idx]
                if mt.get("name") == et.get("name"):
                    total += 1
                    available.remove(idx)
                    e_in = et.get("input", {})
                    m_in = mt.get("input", {})
                    if not e_in and not m_in:
                        matched += 1
                    elif isinstance(e_in, dict) and isinstance(m_in, dict):
                        e_keys = set(e_in.keys())
                        m_keys = set(m_in.keys())
                        if e_keys:
                            key_ov = len(e_keys & m_keys) / len(e_keys)
                            val_m = sum(
                                1
                                for k in e_keys & m_keys
                                if str(e_in[k]).lower() == str(m_in[k]).lower()
                            )
                            val_r = val_m / len(e_keys & m_keys) if (e_keys & m_keys) else 0
                            matched += (key_ov + val_r) / 2
                    break
        param_match = matched / total if total > 0 else 0.0

    return {
        "tool_recall": round(recall, 3),
        "tool_precision": round(precision, 3),
        "order_match": round(order, 3),
        "param_match": round(param_match, 3),
    }


ZERO_JUDGE = {
    "task_fulfillment": 0, "grounding": 0, "tool_appropriateness": 0,
    "parameter_accuracy": 0, "dependency_awareness": 0, "parallelism_and_efficiency": 0,
}
ZERO_METRICS = {"tool_recall": 0.0, "tool_precision": 0.0, "order_match": 0.0, "param_match": 0.0}
ZERO_RESULT = {**ZERO_METRICS, **ZERO_JUDGE}


# ---------------------------------------------------------------------------
# Main evaluation logic
# ---------------------------------------------------------------------------

def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Evaluate agent models on a synthetic MCP benchmark.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument(
        "--benchmark",
        required=True,
        help="Path to benchmark JSONL (from generate_agent_benchmark.py).",
    )
    parser.add_argument(
        "--agent-urls",
        required=True,
        help='JSON dict of server_name → LangGraph agent URL.',
    )
    parser.add_argument(
        "--models",
        nargs="+",
        required=True,
        help="Model names to evaluate (e.g., gpt-4o gpt-4o-mini).",
    )
    parser.add_argument(
        "--model-configs",
        default="{}",
        help='JSON dict of model_name → config overrides (e.g. api_base, api_key).',
    )
    parser.add_argument(
        "--output",
        default="evaluation_results.jsonl",
        help="Output JSONL path (default: evaluation_results.jsonl).",
    )
    parser.add_argument(
        "--env-file",
        default=".env",
        help="Path to .env file for configuration (default: .env).",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    load_dotenv(args.env_file)

    agent_urls: dict[str, str] = json.loads(args.agent_urls)
    model_configs: dict[str, dict] = json.loads(args.model_configs)
    api_key = os.getenv("OPENAI_API_KEY", "")
    judge_model = os.getenv("JUDGE_MODEL", "openai/gpt-4o")

    if not api_key:
        print("ERROR: OPENAI_API_KEY environment variable must be set.", file=sys.stderr)
        sys.exit(1)

    # Load benchmark
    benchmark_path = Path(args.benchmark)
    if not benchmark_path.exists():
        print(f"ERROR: Benchmark file not found: {benchmark_path}", file=sys.stderr)
        sys.exit(1)

    benchmark_df = pd.read_json(benchmark_path, orient="records", lines=True)
    print(f"Loaded {len(benchmark_df)} tasks across {benchmark_df['server'].nunique()} servers")

    # Load the judge flow
    FlowRegistry.discover_flows()
    eval_flow = Flow.from_yaml(FlowRegistry.get_flow_path("Agent Tool-Use Evaluation"))
    eval_flow.set_model_config(model=judge_model, api_key=api_key)
    print(f"Judge model: {judge_model}")
    print(f"Models to evaluate: {args.models}")

    # Check for cached results
    output_path = Path(args.output)
    if output_path.exists():
        cached_df = pd.read_json(output_path, orient="records", lines=True)
        all_results = cached_df.to_dict("records")
        cached_combos = set(zip(cached_df["server"], cached_df["model"]))
        print(f"Loaded {len(all_results)} cached results")
    else:
        all_results = []
        cached_combos = set()

    combos_to_run = [
        (s, m)
        for m in args.models
        for s in benchmark_df["server"].unique()
        if (s, m) not in cached_combos
    ]

    if not combos_to_run:
        print("All model x server combinations are cached.")
    else:
        print(f"Running {len(combos_to_run)} missing combos")

        for server_name, server_tasks in benchmark_df.groupby("server"):
            server_models = [m for s, m in combos_to_run if s == server_name]
            if not server_models:
                continue

            agent_url = agent_urls.get(server_name)
            if not agent_url:
                print(f"SKIP {server_name}: no agent URL - recording zero scores")
                for model in server_models:
                    for idx in range(len(server_tasks)):
                        all_results.append(
                            {"server": server_name, "model": model, "task_idx": idx, **ZERO_RESULT}
                        )
                continue

            safe_name = server_name.replace(" ", "_")
            print(f"\n{'=' * 60}")
            print(f"{server_name} ({len(server_tasks)} tasks)")
            print(f"{'=' * 60}")

            for model in server_models:
                print(f"\n  {model}:", end=" ", flush=True)
                config = model_configs.get(model, {})
                configurable: dict = {"model": model}
                if "api_base" in config:
                    configurable["api_base"] = config["api_base"]
                if "api_key" in config:
                    configurable["api_key"] = config["api_key"]

                agent_block = AgentBlock(
                    block_name=f"eval_{safe_name}",
                    agent_framework="langgraph",
                    agent_url=agent_url,
                    timeout=300.0,
                    input_cols=["question"],
                    output_cols=["agent_response"],
                    connector_kwargs={"run_config": {"configurable": configurable}},
                )
                extractor = AgentResponseExtractorBlock(
                    block_name=f"extract_{safe_name}",
                    agent_framework="langgraph",
                    input_cols="agent_response",
                    extract_text=True,
                    extract_tool_trace=True,
                )

                try:
                    result_df = agent_block.generate(server_tasks[["question"]].copy())
                    result_df = extractor.generate(result_df)
                except Exception as e:
                    print(f"FAILED ({e})")
                    for idx in range(len(server_tasks)):
                        all_results.append(
                            {"server": server_name, "model": model, "task_idx": idx, **ZERO_RESULT}
                        )
                    continue

                text_col = f"extract_{safe_name}_text"
                trace_col = f"extract_{safe_name}_tool_trace"
                judge_rows = []
                task_meta = []

                for idx in range(len(server_tasks)):
                    task = server_tasks.iloc[idx]
                    m_answer = str(result_df[text_col].iloc[idx] or "")
                    m_trace_raw = result_df[trace_col].iloc[idx]
                    m_trace_raw = m_trace_raw if isinstance(m_trace_raw, list) else []

                    m_trace = normalize_tool_trace(m_trace_raw)
                    m_tools = extract_tool_names(m_trace)
                    e_tools = task["expert_tools"]
                    e_trace = task["expert_tool_trace"]
                    metrics = compute_tool_metrics(m_tools, e_tools, m_trace, e_trace)

                    judge_rows.append(
                        {
                            "question": task["question"],
                            "expert_answer_truncated": task["expert_answer"][:2000],
                            "expert_trace_formatted": format_trace_for_judge(e_trace),
                            "model_answer": m_answer[:2000],
                            "model_trace_formatted": format_trace_for_judge(m_trace),
                        }
                    )
                    task_meta.append(
                        {"server": server_name, "model": model, "task_idx": idx, **metrics}
                    )

                if judge_rows:
                    try:
                        judge_ds = Dataset.from_list(judge_rows)
                        judge_result = eval_flow.generate(judge_ds)
                        judge_df = (
                            judge_result.to_pandas()
                            if hasattr(judge_result, "to_pandas")
                            else pd.DataFrame(judge_result)
                        )
                        judge_cols = [
                            "task_fulfillment", "grounding", "tool_appropriateness",
                            "parameter_accuracy", "dependency_awareness", "parallelism_and_efficiency",
                        ]
                        for i, meta in enumerate(task_meta):
                            scores = {}
                            for col in judge_cols:
                                val = judge_df[col].iloc[i] if col in judge_df.columns else 0
                                try:
                                    scores[col] = int(val)
                                except (ValueError, TypeError):
                                    scores[col] = 0
                            all_results.append({**meta, **scores})
                    except Exception as e:
                        print(f"\n    Judge failed: {e}")
                        for meta in task_meta:
                            all_results.append({**meta, **ZERO_JUDGE})

                n = sum(1 for r in all_results if r["model"] == model and r["server"] == server_name)
                avg = np.mean(
                    [r.get("task_fulfillment", 0)
                     for r in all_results if r["model"] == model and r["server"] == server_name]
                )
                print(f"{n} tasks, avg_fulfillment={avg:.1f}")

    # Save results
    results_df = pd.DataFrame(all_results)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    results_df.to_json(output_path, orient="records", lines=True)
    print(f"\nSaved {len(results_df)} results to {output_path}")

    # Print summary
    judge_cols = [
        "task_fulfillment", "grounding", "tool_appropriateness",
        "parameter_accuracy", "dependency_awareness", "parallelism_and_efficiency",
    ]
    tool_cols = ["tool_recall", "tool_precision", "order_match", "param_match"]
    all_cols = tool_cols + judge_cols

    server_model = results_df.groupby(["server", "model"])[all_cols].mean()
    for col in judge_cols:
        server_model[col] = server_model[col] / 10.0
    server_model["overall"] = server_model.mean(axis=1)

    pivot = server_model["overall"].unstack("model")
    col_order = pivot.mean().sort_values(ascending=False).index.tolist()
    pivot = pivot[col_order]

    n_models = results_df["model"].nunique()
    task_counts = results_df.groupby("server").size() // n_models
    pivot.insert(0, "tasks", task_counts)

    pivot.loc["OVERALL"] = pivot.mean()
    pivot.loc["OVERALL", "tasks"] = pivot.loc[pivot.index != "OVERALL", "tasks"].sum()

    print(f"\n{'=' * 80}")
    print("Overall Score by Server x Model")
    print(f"{'=' * 80}")
    print(pivot.round(3).to_string())

    ranking = sorted(col_order, key=lambda m: pivot.loc["OVERALL", m], reverse=True)
    print(f"\nRanking: {' > '.join(ranking)}")


if __name__ == "__main__":
    main()
